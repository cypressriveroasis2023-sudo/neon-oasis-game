#!/usr/bin/env python3
"""Build supabase/seed/install_checklist_seed.sql from model_catalog_v3.csv (spec 1.2)
and the template content in spec section 2.2 / 2.3.

usage: python3 -I tech-checks/watchful-setup/tools/build_catalog.py path/to/model_catalog_v3.csv out.sql
"""
import csv, sys, uuid

CSV, OUT = sys.argv[1], sys.argv[2]
NS = uuid.UUID("6f1c2b0e-0c05-4d1e-9a51-2026112700cc")   # stable ids across rebuilds
def uid(*parts): return str(uuid.uuid5(NS, "|".join(parts)))
def q(v):
    if v is None or v == "": return "null"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, int): return str(v)
    if isinstance(v, (list, tuple)): return "array[" + ",".join(q(x) for x in v) + "]::text[]"
    return "'" + str(v).replace("'", "''") + "'"

ROLE = {
    "Camera system (Avigilon, no config access)": "closed_system",
    "Camera (standalone IPC)": "camera_standalone",
    "PTZ camera (standalone IPC)": "camera_ptz",
    "IP speaker": "ip_speaker",
    "Cloud camera system (Reconeyez)": "cloud_system",
    "Camera on NVR channel": "camera_on_nvr_channel",
    "NVR (recorder)": "nvr",
}
POS = {"nvr": "nvr", "camera_on_nvr_channel": "nvr_channel", "camera_standalone": "standalone",
       "camera_ptz": "ptz", "ip_speaker": "speaker", "cloud_system": "cloud", "closed_system": "closed"}
UNIT_TYPES = [("Spotter (NVR trailer)", True), ("Solar Spotter (SS)", True), ("Helios", False),
              ("Ranger", False), ("Sniper", False), ("CAM V / RSU", False), ("Recon (Reconeyez)", False),
              ("Recon II (Reconeyez)", False), ("Wall-E", False)]

rows = list(csv.DictReader(open(CSV, newline="", encoding="utf-8-sig")))
assert len(rows) == 36, f"expected 36 catalog rows, got {len(rows)}"

def n(v):
    try: return int(v)
    except (TypeError, ValueError): return None

sql = ["-- generated by watchful-setup/tools/build_catalog.py from model_catalog_v3.csv -- do not hand-edit",
       "select set_config('cos.audit_reason', 'seed: model_catalog_v3.csv + spec v1.0 section 2.2', true);"]
for i, (ut, rec) in enumerate(UNIT_TYPES):
    sql.append(f"insert into app_private.ws_unit_types values ({q(ut)}, {q(rec)}, {i});")

models, links, gaps = {}, [], []
for r in rows:
    if r["device_role"] == "(model not on file)":
        gaps.append(r); continue
    role = ROLE[r["device_role"]]
    key = (r["brand"], r["model"], role)
    if r["model"].startswith("ALI-"):
        status = "UNCONFIRMED"
    else:
        status = "UNCONFIRMED" if role in ("closed_system", "cloud_system", "ip_speaker") else "UNCONFIRMED"
    m = models.setdefault(key, dict(id=uid("model", *key), role=role, brand=r["brand"], model=r["model"],
        fw=set(), ref_std=r["reference_standard"], ref_units=r["reference_units"],
        checklist=r["setup_checklist"], source=r["source"], status=status))
    m["fw"].update(x.strip() for x in r["firmware_seen"].split(";") if x.strip())
    links.append((r["unit_type"], m["id"], POS[role], r))

for m in models.values():
    sql.append("insert into app_private.ws_device_models(id, device_role, brand, model, firmware_seen, reference_standard, "
               "reference_units, setup_checklist, standard_status, source) values (" + ", ".join([
               q(m["id"]), q(m["role"]), q(m["brand"]), q(m["model"]), q("; ".join(sorted(m["fw"]))),
               q(m["ref_std"]), q(m["ref_units"]), q(m["checklist"]), q(m["status"]), q(m["source"])]) + ");")
for ut, mid, pos, r in links:
    sql.append("insert into app_private.ws_unit_type_models values (" + ", ".join([q(ut), q(mid), q(pos),
        q(n(r["units_with_this_model"])), q(n(r["units_field"])), q(n(r["units_shop"])),
        q(n(r["units_not_in_tracker"])), q(n(r["devices_or_channels"])), q(n(r["sites"])), q(r["example_units"])]) + ");")
# spec 1.2 table: "Recon (Reconeyez): same as Recon II" -> offer the Reconeyez system there too
recon = models[("Reconeyez", "model not recorded in COS/Watchful", "cloud_system")]
sql.append(f"insert into app_private.ws_unit_type_models(unit_type, device_model_id, position) values ('Recon (Reconeyez)', {q(recon['id'])}, 'cloud');")
for g in gaps:
    sql.append("insert into app_private.ws_unit_type_model_gaps values (" + ", ".join([q(g["unit_type"]),
        q(n(g["units_with_this_model"])), q(n(g["units_field"])), q(n(g["units_shop"])),
        q(g["reference_standard"]), q(g["source"])]) + ");")

# ------------------------------------------------------------------ templates (spec 2.2)
HOURS = ["24/7", "Customer hours: nights and weekends", "Customer hours: nights only",
         "Customer hours: weekends only", "Customer hours: other (see note)"]
MOTION = ["On + Email", "On, not emailed", "Off"]

def item(code, title, standard, status, *, repeat="once", vtype="none", opts=None, ev="optional",
         group=None, required=True, ph=None, help=None, instr=None):
    return dict(code=code, title=title, standard=standard, status=status, repeat=repeat, vtype=vtype,
                opts=opts, ev=ev, group=group, required=required, ph=ph, help=help, instr=instr)

def mail(kind, repeat):
    login = ("The unit's Watchful token only. Tick \"done\"; never type the value into COS." if kind == "nvr"
             else "The full token email address. Tick \"done\"; never type the value into COS.")
    sender = "Same as recipient 1 (the unit's token address)"
    return [
        item("M1", "Mail server", "smtp.watchful.cloud, port 8086", "CONFIRMED", repeat=repeat, ev="required", group="mail_page",
             instr="Screenshot the mail page. Cover the login field before uploading."),
        item("M2", "Authentication", "On", "CONFIRMED", repeat=repeat, ev="required", group="mail_page"),
        item("M3", "SSL", "Off", "CONFIRMED", repeat=repeat, ev="required", group="mail_page"),
        item("M4", "Login", login, "CONFIRMED", repeat=repeat, ev="never", instr="Do not photograph this field."),
        item("M5", "Sender", sender, "CONFIRMED", repeat=repeat),
        item("M6", "Recipients", "Exactly 1 (the token address)", "CONFIRMED", repeat=repeat),
        item("M7", "Attach snapshot", "On, interval 2", "CONFIRMED", repeat=repeat),
        item("M8", "Sender display name", "\"Watchful\" (cosmetic, not required for sign-off)", "CONFIRMED",
             repeat=repeat, required=False),
    ]

NVR_HELP = {
    "ALI-NR040F-1": "NR040F-1 references: motion on and emailed on 12 of 20 channels (the email link is set on 16 of 20); "
                    "intrusion on and emailed on 18 of 20. Two channels send with intrusion off.",
    "ALI-NR041F-1": "NR041F-1 references: motion on 12/12, emailed 10/12; intrusion emailed on only 6/12.",
    "ALI-NR042F-1": "NR042F-1 has no working reference; it borrows the NR040F/041F standard.",
    "ALI-NR042F-1-D": "One working reference (SS_NVR 310): sends on all 4 channels with intrusion on + emailed + area, "
                      "motion on but NOT emailed, 24/7.",
    None: "Model not on file: generic recorder standard until the office maps the model.",
}
def nvr_items(model):
    d = model == "ALI-NR042F-1-D"
    h = NVR_HELP[model]
    it = mail("nvr", "once") + [
        item("N1", "Motion detection", "On (Email optional: the one reference has motion on but not emailed)" if d
             else "On + Email + snapshot + upload", "UNCONFIRMED", repeat="channel", vtype="enum", opts=MOTION,
             ev="recommended", help=h),
        item("N2", "Intrusion detection", "On + Email + snapshot + upload", "UNCONFIRMED", repeat="channel",
             ev="recommended", help=h),
        item("N3", "Intrusion area drawn", "Yes" if d else "Yes, covers the area the customer wants watched",
             "UNCONFIRMED", repeat="channel", ev="required", help=h, instr="Screenshot the intrusion area for this channel."),
        item("N4", "Arming schedule", "24/7 unless the customer has set hours (record the hours)", "UNCONFIRMED",
             repeat="channel", vtype="hours", opts=HOURS, help=h),
    ]
    if model:
        it.append(item("N5", "Confirmed event path", "Pending: confirmed by the read-only event check", "PLACEHOLDER",
                       repeat="channel", ph=f"{{{{CONFIRMED_EVENT_PATH_NVR_{model}}}}}"))
    return it

IPC_HELP = {
    "ALI-PB81-AI-D": "References: motion on for 11/23, 24/7 arming on 13/23.",
    "ALI-PB40-UAIS-D": "References: 7/13 armed nights and weekends.",
    "ALI-FB21-A": "References: motion off on all.",
    "ALI-PB50-LUAIS-D": "References: intrusion emailed on only 6/12.",
    "ALI-PZ40-UZAI-D": "References: intrusion emailed on 4/7; the motion-email value reads \"2\" on all 7 and its meaning "
                       "is not confirmed ({{CONFIRMED_MOTION_EMAIL_VALUE_2_MEANING}}).",
    "ALI-PT80-LUAIS-D": "References: intrusion emailed on 5/9.",
}
NO_REF = {"ALI-PB50-LUAIS", "ALI-PB80-LUAIS", "ALI-PB80-LUAIS-D", "ALI-FB41-LUA-D", "ALI-PT50-LUAIS-D", "ALI-PT80-LUAIS"}
IPC_MODELS = ["ALI-PB81-AI-D", "ALI-PB81-AI", "ALI-PB40-UAIS-D", "ALI-PB50-LUAIS", "ALI-PB50-LUAIS-D", "ALI-PB80-LUAIS",
              "ALI-PB80-LUAIS-D", "ALI-FB21-A", "ALI-FB41-UA-D", "ALI-FB41-LUA-D", "ALI-PZ40-UZAI-D", "ALI-PT50-LUAIS-D",
              "ALI-PT80-LUAIS", "ALI-PT80-LUAIS-D"]

def physical(standalone):
    return [
        item("P1", "Camera online", "Online on the unit network" if standalone else "Camera online in the NVR",
             "CONFIRMED", repeat="camera"),
        item("P2", "Image clear day and night", "Clear image, day and night", "CONFIRMED", repeat="camera", ev="required",
             instr="Attach one day image of this camera."),
        item("P3", "Aimed per site plan", "Aimed per the site plan", "CONFIRMED", repeat="camera", ev="recommended"),
        item("P4", "Name label", "Camera name matches the COS camera name" if standalone
             else "Channel label matches the COS camera name", "CONFIRMED", repeat="camera"),
    ]

def ipc_items(model):
    if model is None: h = "Model not on file: generic camera standard until the office maps the model."
    elif model in NO_REF: h = "No working reference yet for this model: generic camera standard."
    else: h = IPC_HELP.get(model)
    it = physical(True) + mail("camera", "camera") + [
        item("C1", "Intrusion detection", "On + Email (linkage enabled) + upload", "UNCONFIRMED", repeat="camera",
             ev="recommended", help=h),
        item("C2", "Intrusion area drawn", "Yes", "UNCONFIRMED", repeat="camera", ev="required", help=h,
             instr="Screenshot the intrusion area for this camera."),
        item("C3", "Motion detection", "Optional (most working cameras have it off). Record on/off", "UNCONFIRMED",
             repeat="camera", vtype="enum", opts=MOTION, help=h),
        item("C4", "Arming schedule", "Customer hours (24/7 if none given). Record the hours", "UNCONFIRMED",
             repeat="camera", vtype="hours", opts=HOURS, help=h),
    ]
    if model:
        it.append(item("C5", "Confirmed event path", "Pending: confirmed by the read-only event check", "PLACEHOLDER",
                       repeat="camera", ph=f"{{{{CONFIRMED_EVENT_PATH_IPC_{model}}}}}"))
    return it

templates = []   # (key parts, model_id|None, role|None, scope, name, items)
def mid(brand, model, role): return models[(brand, model, role)]["id"]

templates.append((None, None, "unit", "Unit-level items", [
    item("U1", "Power", "Power on and stable", "CONFIRMED"),
    item("U2", "Mounting", "Mounted and secure", "CONFIRMED"),
    item("U3", "Network up", "Unit connection is up", "CONFIRMED"),
    item("U4", "Unit name matches COS", "Unit name on the device and in Watchful matches COS", "CONFIRMED"),
    item("U5", "Right site in Watchful", "Unit is on the right site in Watchful", "CONFIRMED"),
]))
templates.append((None, None, "watchful", "Watchful items (Alibi units)", [
    item("W1", "Device added in Watchful", "Device added in Watchful on the right site", "CONFIRMED"),
    item("W2", "Camera mapped and named", "Mapped to the right feed and named to the naming convention", "CONFIRMED",
         repeat="camera"),
]))
for nm in ["ALI-NR040F-1", "ALI-NR041F-1", "ALI-NR042F-1", "ALI-NR042F-1-D"]:
    templates.append((mid("Alibi (Uniview OEM)", nm, "nvr"), None, "nvr", f"Recorder {nm}", nvr_items(nm)))
templates.append((None, "nvr", "nvr", "Recorder (generic, model not on file)", nvr_items(None)))
for nm in IPC_MODELS:
    role = "camera_ptz" if nm == "ALI-PZ40-UZAI-D" else "camera_standalone"
    templates.append((mid("Alibi (Uniview OEM)", nm, role), None, "camera", f"Camera {nm}", ipc_items(nm)))
templates.append((None, "camera_standalone", "camera", "Standalone camera (generic)", ipc_items(None)))
templates.append((None, "camera_ptz", "camera", "PTZ camera (generic)", ipc_items(None)))
templates.append((None, "camera_on_nvr_channel", "camera", "Camera on NVR channel (physical)", physical(False)))
templates.append((None, "ip_speaker", "camera", "IP speaker", [
    item("S1", "Speaker online", "Online", "CONFIRMED", repeat="camera"),
    item("S2", "Audio test heard on site", "Audio test heard on site", "CONFIRMED", repeat="camera"),
]))
avig = [
    item("A1", "Unit added in Watchful", "Unit added in Watchful on the right site. Never log in to the Avigilon system.", "CONFIRMED"),
    item("A2", "Camera mapped and named", "Mapped and named to the naming convention", "CONFIRMED", repeat="camera"),
    item("A3", "Device Health", "Watchful Device Health shows Healthy", "CONFIRMED", ev="required"),
]
recn = [
    item("R1", "Reconeyez integration", "Watchful-side Reconeyez integration set up", "CONFIRMED"),
    item("R2", "Camera mapped, area set", "Each camera mapped and its area set in Watchful", "CONFIRMED", repeat="camera"),
    item("R3", "Device Health", "Watchful Device Health shows Healthy", "CONFIRMED", ev="required"),
]
templates.append((mid("Avigilon", "model not recorded in COS/Watchful", "closed_system"), None, "watchful", "Avigilon (Watchful side only)", avig))
templates.append((None, "closed_system", "watchful", "Avigilon (generic)", avig))
templates.append((mid("Reconeyez", "model not recorded in COS/Watchful", "cloud_system"), None, "watchful", "Reconeyez (Watchful side only)", recn))
templates.append((None, "cloud_system", "watchful", "Reconeyez (generic)", recn))

placeholders = {}
for model_id, role, scope, name, items in templates:
    tid = uid("tpl", str(model_id), str(role), scope, "1")
    sql.append("insert into app_private.ws_checklist_templates(id, device_model_id, device_role, scope, name, version, status) "
               f"values ({q(tid)}, {q(model_id)}, {q(role)}, {q(scope)}, {q(name)}, 1, 'draft');")
    for k, it in enumerate(items):
        sql.append("insert into app_private.ws_checklist_template_items(template_id, code, title, standard, instructions, help_text, "
                   "standard_status, repeat_per, value_type, value_options, evidence, evidence_group, required, placeholder_key, "
                   "sort_order) values (" + ", ".join([q(tid), q(it["code"]), q(it["title"]), q(it["standard"]),
                   q(it["instr"]), q(it["help"]), q(it["status"]), q(it["repeat"]), q(it["vtype"]), q(it["opts"]) if it["opts"] else "null",
                   q(it["ev"]), q(it["group"]), q(it["required"]), q(it["ph"]), q(k * 10)]) + ");")
        if it["ph"]: placeholders[it["ph"]] = f"{name}: {it['title']}"
    sql.append(f"update app_private.ws_checklist_templates set status = 'published', published_at = now(), "
               f"change_note = 'v1 seed from spec 2.2 (2026-11-27)' where id = {q(tid)};")
placeholders["{{CONFIRMED_MOTION_EMAIL_VALUE_2_MEANING}}"] = "Help text: meaning of camera motion-email value \"2\""
for k, d in placeholders.items():
    sql.append(f"insert into app_private.ws_placeholders(key, description) values ({q(k)}, {q(d)});")

sql.append("insert into app_private.ws_notices values ('standard_unconfirmed', 'Standard unconfirmed', " + q(
    "The exact event path into Watchful is being confirmed right now by a read-only check. On 11/27, 13 working cameras "
    "(Helios 010 and 011 Cams 1-3, Rangers 011, 012, 017 and 028, Solar Spotter 235 Cams 1, 2 and 4) sent events while both "
    "motion and intrusion were turned off. So motion and intrusion email are not the only way events reach Watchful. Until the "
    "check finishes, the event items describe what working units have in common. They are not a proven recipe.") + ");")
sql.append("insert into app_private.ws_notices values ('evidence_upload', 'Before you upload', "
           "'Cover or crop any password, token, IP address or serial number.');")
sql.append(f"-- loaded: {len(rows)} catalog rows = {len(links)} unit-type/model rows ({len(models)} distinct models) + {len(gaps)} model-not-on-file rows; "
           f"{len(templates)} templates; {len(placeholders)} placeholders")
open(OUT, "w").write("\n".join(sql) + "\n")
print(f"{len(rows)} rows -> {len(links)} links, {len(models)} models, {len(gaps)} gaps, {len(templates)} templates, {len(placeholders)} placeholders")
