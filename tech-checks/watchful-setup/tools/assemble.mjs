// Builds tech-checks/database-maintenance/watchful-setup-check-v1.sql from watchful-setup/sql/*.sql.
// node tech-checks/watchful-setup/tools/assemble.mjs        (write)
// node tech-checks/watchful-setup/tools/assemble.mjs --check (exit 1 if the file is out of date)
import {readFileSync, writeFileSync, readdirSync} from 'node:fs';
const dir = new URL('../sql/', import.meta.url), out = new URL('../../database-maintenance/watchful-setup-check-v1.sql', import.meta.url);
const parts = readdirSync(dir).filter(f => f.endsWith('.sql')).sort();
const text = ['-- Watchful setup check v1 for Tech Check (goqrnolcvqnirjmzaeyk). NOT APPLIED until James says go.',
  '-- Generated by tech-checks/watchful-setup/tools/assemble.mjs from watchful-setup/sql/' + parts.join(', ') + '. Do not hand-edit.',
  'begin;', ...parts.map(f => '\n-- ================== ' + f + '\n' + readFileSync(new URL(f, dir), 'utf8').trim()), 'commit;', ''].join('\n');
if (process.argv.includes('--check')) {
  let now = ''; try { now = readFileSync(out, 'utf8'); } catch {}
  if (now !== text) { console.error('watchful-setup-check-v1.sql is out of date: run node tech-checks/watchful-setup/tools/assemble.mjs'); process.exit(1); }
  console.log('watchful-setup-check-v1.sql is current');
} else { writeFileSync(out, text); console.log('wrote', out.pathname); }
