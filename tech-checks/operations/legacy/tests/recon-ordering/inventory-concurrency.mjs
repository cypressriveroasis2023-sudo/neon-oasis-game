 async function waitBlocked(client) {
  const until = Date.now() + 5000;
  while (Date.now() < until) {
   const row = await one(observer, 'SELECT wait_event_type,wait_event FROM pg_stat_activity WHERE pid=$1', [client.processID]);
   if (row?.wait_event_type === 'Lock') return;
   await delay(20);
  }
  throw Error('Expected a real PostgreSQL lock wait, not merely concurrent promises.');
 }
