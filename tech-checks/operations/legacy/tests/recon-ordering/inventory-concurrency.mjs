export function validateInventoryTestUrl(raw) {
 if (!raw) throw Error('Set RECON_INVENTORY_TEST_DATABASE_URL to a new disposable loopback recon_inventory_test_* database.');
 const url = new URL(raw);
 if (!['postgres:', 'postgresql:'].includes(url.protocol) || url.search || url.hash ||
     !['127.0.0.1', 'localhost', '[::1]'].includes(url.hostname) || !/^\/recon_inventory_test_[a-z0-9_]+$/.test(url.pathname))
  throw Error('Refusing anything except a disposable loopback recon_inventory_test_* database without connection overrides.');
 return url;
}

