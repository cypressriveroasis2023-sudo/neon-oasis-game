// Generates reviewed SQL only. Never connects to a database or deploys anything.
import {readFile,writeFile} from 'node:fs/promises';
import {baselineSql,candidateSql,baselineCatalog,catalogSql} from '../tests/fixtures/placement-snapshot-dedup.mjs';
const candidateCatalog=JSON.parse(await readFile(new URL('../tests/fixtures/placement-snapshot-dedup-catalog.json',import.meta.url),'utf8'));
const guard=(expected,label)=>`do $catalog_guard$
declare actual jsonb;
begin
 select jsonb_agg(to_jsonb(c) order by c.schema,c.name) into actual from (${catalogSql}) c;
 if actual is distinct from $expected_catalog$${JSON.stringify(expected)}$expected_catalog$::jsonb then
  raise exception '${label}: live function body or security catalog changed; stop and review' using errcode='55000';
 end if;
end $catalog_guard$;`;
const opening=`-- Generated by scripts/build-placement-snapshot-dedup.mjs. Read-adapter DDL only.
-- Requires a separately authorized production maintenance window; this file does not authorize rollout.
-- No source, assignment, telemetry, credential, ACL, timeout or Edge changes.
begin;
set local lock_timeout='2s';
do $migration_lock$ begin
 if not pg_try_advisory_xact_lock(hashtextextended('COS_PLACEMENT_SNAPSHOT_DEDUP_V1',0)) then
  raise exception 'Snapshot adapter migration is already running' using errcode='55P03';
 end if;
end $migration_lock$;
`;
const restore=['cos_mhelp_placement_private.upload_snapshot','public.cos_mhelp_placement_snapshot'].map(name=>{
 const start=baselineSql.indexOf('CREATE OR REPLACE FUNCTION '+name+'(');
 if(start<0)throw Error('Missing exact baseline '+name);
 const end=baselineSql.indexOf('$function$;',baselineSql.indexOf('AS $function$',start));
 if(end<0)throw Error('Unterminated baseline '+name);
 return baselineSql.slice(start,end+'$function$;'.length);
}).join('\n\n');
await writeFile(new URL('../db/mhelp-placement-snapshot-dedup-install.sql',import.meta.url),opening+guard(baselineCatalog,'Install precondition')+'\n'+candidateSql+'\n'+guard(candidateCatalog,'Install postcondition')+'\ncommit;\n');
await writeFile(new URL('../db/mhelp-placement-snapshot-dedup-rollback.sql',import.meta.url),opening+guard(candidateCatalog,'Rollback precondition')+'\n'+restore+'\n'+guard(baselineCatalog,'Rollback postcondition')+'\ncommit;\n');
console.log('Generated exact-catalog guarded install and rollback; no database contacted.');
