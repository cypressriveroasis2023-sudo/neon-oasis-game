// Deterministic generic SQL generation only. Never connects to a database or deploys.
import {readFile,writeFile} from 'node:fs/promises';
import assert from 'node:assert/strict';
import {createHash} from 'node:crypto';
const read=path=>readFile(new URL(path,import.meta.url),'utf8');
const catalog=JSON.parse(await read('../tests/fixtures/placement-label-index-catalog.json'));
const candidate=await read('../db/mhelp-placement-label-index.sql');
const baseline=await read('../tests/fixtures/placement-label-index-baseline.sql');
assert.equal(catalog.baseline.length,8);assert.equal(catalog.candidate.length,8);
assert.equal((candidate.match(/pg_catalog\.regexp_replace\(pg_catalog\.lower\(x\.unit_number\)/g)||[]).length,3);
// Pin the generic code inputs to the same canonical bodies guarded at execution.
for(const [sql,rows] of [[baseline,catalog.baseline],[candidate,catalog.candidate]]){
 for(const [schema,name] of [['app_private','cos_source_native_guard'],['cos_mhelp_placement_private','guard']]){
  const start=sql.indexOf(`CREATE OR REPLACE FUNCTION ${schema}.${name}(`);
  assert.ok(start>=0,`Missing exact ${schema}.${name}`);
  const body=sql.indexOf('AS $function$',start);
  const end=sql.indexOf('$function$',body+'AS $function$'.length)+'$function$'.length;
  assert.ok(body>=start&&end>body,`Invalid definition ${schema}.${name}`);
  const definition=sql.slice(start,end)+'\n';
  const sha=createHash('sha256').update(definition).digest('hex');
  assert.equal(sha,rows.find(r=>r.schema===schema&&r.name===name).definition_sha256,`Code/catalog fingerprint drift for ${schema}.${name}`);
 }
}

const signatureSql=catalog.signatures.map(s=>`to_regprocedure('${s}')`).join(',');
const fullCatalogSql=`select coalesce(jsonb_agg(to_jsonb(p)-'prosrc' order by p.oid),'[]'::jsonb) from pg_proc p where p.oid=any(array[${signatureSql}]::oid[])`;
const tableSecuritySql=`select jsonb_build_object('owner',c.relowner,'acl',c.relacl,'rls',c.relrowsecurity,'force_rls',c.relforcerowsecurity,'columns',(select jsonb_agg(jsonb_build_object('name',a.attname,'acl',a.attacl) order by a.attnum) from pg_attribute a where a.attrelid=c.oid and a.attnum>0 and not a.attisdropped)) from pg_class c where c.oid='public.equipment_units'::regclass`;
const catalogValueSql=`select coalesce(jsonb_agg(to_jsonb(q) order by q.schema,q.name),'[]'::jsonb) from (${catalog.catalogSql}) q`;
const expected=v=>`$expected$${JSON.stringify(v)}$expected$::jsonb`;
const opening=`-- Generated by scripts/build-placement-label-index.mjs. Generic reviewed DDL, not authorization to execute.
-- Preserve whole current graph/digest, Owner edits, errors, ACLs and caller statement_timeout.
-- No data writes, grants, ANALYZE, timeout increase, Edge change, or persistent cache.
begin;
set local lock_timeout='2s';
set local search_path=pg_catalog,pg_temp;
do $migration$
declare actual jsonb; actual_index jsonb; index_oid oid; before_proc jsonb; after_proc jsonb;
 before_security jsonb; after_security jsonb;
begin
 if not pg_try_advisory_xact_lock(hashtextextended('COS_PLACEMENT_LABEL_INDEX_V1',0)) then
  raise exception 'Placement label index maintenance is already running' using errcode='55P03';
 end if;
 if array_position(array[${signatureSql}]::oid[],null) is not null then
  raise exception 'Placement label index precondition: a required function is missing' using errcode='55000';
 end if;
 ${catalogValueSql} into actual;
 select to_regclass('public.cos_equipment_unit_source_label_hash')::oid into index_oid;
 select q.value into actual_index from (${catalog.indexSql}) q;
`;
function script(install){
 const expectedFrom=install?catalog.baseline:catalog.candidate,expectedTo=install?catalog.candidate:catalog.baseline;
 const label=install?'Install':'Rollback';
 const noOpIndex=install?`actual_index is not distinct from ${expected(catalog.index)}`:'index_oid is null';
 const requiredIndex=install?'index_oid is null':`actual_index is not distinct from ${expected(catalog.index)}`;
 const body=install?candidate:`drop index public.cos_equipment_unit_source_label_hash;\n${baseline}`;
 return opening+` -- Exact already-complete state is an idempotent no-op. Drift is never accepted as success.
 if actual is not distinct from ${expected(expectedTo)} and ${noOpIndex} then
  return;
 end if;
 if actual is distinct from ${expected(expectedFrom)} or not (${requiredIndex}) then
  raise exception '${label} precondition: function/helper/catalog/index changed; stop and review' using errcode='55000';
 end if;
 ${fullCatalogSql} into before_proc;
 ${tableSecuritySql} into before_security;
 execute $change$${body}$change$;
 ${catalogValueSql} into actual;
 ${fullCatalogSql} into after_proc;
 ${tableSecuritySql} into after_security;
 select to_regclass('public.cos_equipment_unit_source_label_hash')::oid into index_oid;
 select q.value into actual_index from (${catalog.indexSql}) q;
 if actual is distinct from ${expected(expectedTo)}
  or before_proc is distinct from after_proc
  or before_security is distinct from after_security
  or not (${noOpIndex}) then
  raise exception '${label} postcondition: function/catalog/index/security mismatch; transaction must roll back' using errcode='55000';
 end if;
end $migration$;
commit;
`;
}
for(const [name,isInstall] of [['install',true],['rollback',false]])await writeFile(new URL(`../db/mhelp-placement-label-index-${name}.sql`,import.meta.url),script(isInstall));
console.log('Generated fingerprint-guarded label-index install/rollback; no database contacted.');
