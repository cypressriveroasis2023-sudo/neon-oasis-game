import test from 'node:test';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {PGlite} from '@electric-sql/pglite';

const root = new URL('../../', import.meta.url);
const migration = readFileSync(new URL('supabase/migrations/20261118_camera_unit_routers_read_grants.sql', root), 'utf8');
const rollback = readFileSync(new URL('operations/db/20261118_camera_unit_routers_read_grants_rollback.sql', root), 'utf8');
const pages = readFileSync(new URL('supabase/functions/cos-operations-pages/index.ts', root), 'utf8');
const fleetAccess = readFileSync(new URL('supabase/functions/cos-operations-pages/fleetAccess.ts', root), 'utf8');
const sweep = readFileSync(new URL('supabase/functions/camera-health-sweep/index.ts', root), 'utf8');
const cameraHealth = readFileSync(new URL('camera-health.html', root), 'utf8');
const unitStatus = readFileSync(new URL('supabase/functions/cos-unit-camera-status/dist/index.ts', root), 'utf8');

const kept = ['SELECT'];
const originalPrivileges = ['DELETE', 'INSERT', 'MAINTAIN', 'REFERENCES', 'SELECT', 'TRIGGER', 'TRUNCATE', 'UPDATE'];
const readers = ['postgres', 'anon', 'authenticated', 'service_role'];

function grantsOf(rows, table = 'camera_unit_routers') {
  return rows
    .filter(row => row.table_name === table)
    .map(row => [row.grantee, row.privilege_type, row.is_grantable, row.grantor].join('|'))
    .sort();
}

test('router status reads need authenticated SELECT and no anon privilege', () => {
  assert.match(pages, /const headers = \{ apikey: LEGACY_PUBLISHABLE_KEY, Authorization: authorization, Accept: 'application\/json' \}/);
  assert.match(pages, /if \(!context\.legacyOwner && !\(verifiedFleetIt && fleetRouteAllowed\(method,path\)\)\) fail\('An active COS Owner account is required\.', 403\)/);
  const routersAt = pages.indexOf("if (path === '/api/routers')");
  const gateAt = pages.indexOf("if (!context.legacyOwner && !(verifiedFleetIt && fleetRouteAllowed(method,path)))");
  assert.ok(gateAt > 0 && routersAt > gateAt, 'the routers read stays behind the existing gate');
  assert.match(pages, /legacyAll\('camera_unit_routers\?select=[^']+', context\.headers\)/);
  assert.match(unitStatus, /legacyAll\("camera_unit_routers\?select=[^"]+", context\.headers\)/);
  assert.match(fleetAccess, /'\/api\/routers'/);
  assert.match(cameraHealth, /db\.from\('camera_unit_routers'\)\.select\('\*'\)/);
  assert.match(sweep, /SUPABASE_SERVICE_ROLE_KEY/);
  assert.match(sweep, /\.from\("camera_unit_routers"\)/);
  assert.match(sweep, /\.update\(patch\)/);
  const statements = migration.replace(/--[^\n]*/g, '');
  assert.doesNotMatch(statements, /service_role|camera_devices|camera_health|policy|row level security/i);
  assert.match(statements, /revoke all on table public\.camera_unit_routers from anon, authenticated;/);
  assert.match(statements, /grant select on table public\.camera_unit_routers to authenticated;/);
  assert.doesNotMatch(statements, /grant\s+(insert|update|delete|truncate|all)/i);
});

test('migration and rollback restore the captured router grants inside a transaction', async () => {
  const db = new PGlite();
  try {
    await db.exec('create role anon; create role authenticated; create role service_role;');
    await db.exec('begin');
    await db.exec(`
      create table public.camera_unit_routers (id bigint generated by default as identity primary key);
      create table public.grant_control (id int);
      grant all on table public.camera_unit_routers to postgres, anon, authenticated, service_role;
      grant all on table public.grant_control to anon, authenticated, service_role;
      create policy camera_unit_routers_read_probe on public.camera_unit_routers for select to authenticated using (true);
    `);
    const readGrants = async () => (await db.query(`
      select c.relname as table_name, r.rolname as grantee, a.privilege_type, a.is_grantable, g.rolname as grantor
      from pg_class c
      join pg_namespace n on n.oid = c.relnamespace
      cross join lateral aclexplode(c.relacl) a
      join pg_roles r on r.oid = a.grantee
      join pg_roles g on g.oid = a.grantor
      where n.nspname = 'public' and c.relname in ('camera_unit_routers', 'grant_control')
    `)).rows;
    const readPolicies = async () => (await db.query(`
      select polname, polcmd, polroles::text as roles, polqual is not null as has_using
      from pg_policy
      where polrelid = 'public.camera_unit_routers'::regclass
      order by polname
    `)).rows;
    const readSequence = async () => (await db.query(`
      select relacl::text as acl
      from pg_class
      where relname = 'camera_unit_routers_id_seq'
    `)).rows[0].acl;

    const original = grantsOf(await readGrants());
    const controlBefore = grantsOf(await readGrants(), 'grant_control');
    const policiesBefore = await readPolicies();
    const sequenceBefore = await readSequence();
    assert.deepEqual(original, readers.flatMap(role => originalPrivileges.map(privilege => `${role}|${privilege}|false|postgres`)).sort());

    await db.exec(migration);
    const tightened = grantsOf(await readGrants());
    assert.deepEqual(
      tightened.filter(row => row.startsWith('anon|') || row.startsWith('authenticated|')),
      kept.map(privilege => `authenticated|${privilege}|false|postgres`),
    );
    assert.deepEqual(
      tightened.filter(row => row.startsWith('postgres|') || row.startsWith('service_role|')),
      original.filter(row => row.startsWith('postgres|') || row.startsWith('service_role|')),
    );
    assert.deepEqual(grantsOf(await readGrants(), 'grant_control'), controlBefore);
    assert.deepEqual(await readPolicies(), policiesBefore);
    assert.equal(await readSequence(), sequenceBefore);

    await db.exec(rollback);
    assert.deepEqual(grantsOf(await readGrants()), original);
    assert.deepEqual(grantsOf(await readGrants(), 'grant_control'), controlBefore);
    assert.deepEqual(await readPolicies(), policiesBefore);
    assert.equal(await readSequence(), sequenceBefore);

    await db.exec('rollback');
    const gone = await db.query("select to_regclass('public.camera_unit_routers') as name");
    assert.equal(gone.rows[0].name, null);
  } finally {
    await db.close();
  }
});
