import {test,expect} from '@playwright/test';
import {mountFleet} from './fleet-dashboard-fixtures.mjs';
import {fieldProductFixture} from './fixtures/mhelp-field-health-fixtures.mjs';
test('Camera Health provider filters retain Product IDs, observations and unresolved details without writes',async({page},info)=>{
 const f=fieldProductFixture();
 const {app,state}=await mountFleet(page,false,{hash:'#camera-health',field:f.field,health:f.health});
 const panel=app.getByRole('region',{name:'Field equipment by provider'});
 await expect(panel).toBeVisible();
 for(const name of ['Star4Live','Avigilon','Reconeyez','Other equipment'])await expect(panel.getByRole('heading',{name,exact:true})).toBeVisible();
 const star=panel.getByRole('article',{name:'Star4Live Field equipment'});
 await star.getByRole('button',{name:/Offline$/,exact:false}).first().click();
 await expect(star.locator('li')).toHaveCount(1);
 await expect(star.locator('li')).toContainText('Product 1002');
 await expect(star.locator('li')).toContainText('Star4Live');
 await star.getByLabel('Star4Live status filter').selectOption('unverified');
 await star.getByLabel('Search Star4Live equipment').fill('1006');
 await expect(star.locator('li')).toHaveCount(1);
 await star.getByRole('button',{name:'Review unit →'}).click();
 await expect(panel.getByRole('region',{name:'Selected camera equipment'})).toContainText('Product 1006');
 await expect(panel.getByRole('region',{name:'Selected camera equipment'})).toContainText('No uniquely verified COS unit link');
 const width=await panel.evaluate(e=>({client:e.clientWidth,scroll:e.scrollWidth}));expect(width.scroll).toBeLessThanOrEqual(width.client+2);
 await page.screenshot({path:info.outputPath('cos-camera-provider-details.png'),fullPage:true});
 state.fail=true;await app.locator('.cos-fleet-refresh').click();
 await expect(panel.getByText('Current camera-health evidence is unavailable or incomplete.',{exact:false})).toBeVisible();
 await expect(star.locator('.cos-provider-status-online b')).toHaveText('0');
 await expect(star.locator('.cos-provider-status-offline b')).toHaveText('0');
 await expect(star.locator('.cos-provider-total')).toHaveText('6');
 expect(state.calls.every(call=>call.method==='GET')).toBe(true);expect(state.errors).toEqual([]);
});
