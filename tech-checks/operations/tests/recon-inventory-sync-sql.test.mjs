test('refresh retains an original bridge event only for unchanged exact group membership and never borrows the inventory observation time', async () => {
 const history = timestamp(-10000);
 for (const [index, scenario] of ['same-group', 'incoming-event', 'changed-area', 'changed-membership', 'changed-bridge-keys', 'changed-detector-keys', 'malformed-time', 'future-time'].entries()) {
  const initial = await request({at: timestamp(index * 5000)});
  initial.p_identity_inventory.groups[0].bridgeLastEventAt = scenario === 'malformed-time' ? 'invalid' : scenario === 'future-time' ? timestamp(50000) : history;
  if (scenario === 'changed-bridge-keys') initial.p_identity_inventory.groups[0].bridgeKeys = ['a'.repeat(64)];
  if (scenario === 'changed-detector-keys') initial.p_identity_inventory.groups[0].detectorKeys[0] = 'b'.repeat(64);
  if (scenario === 'malformed-time' || scenario === 'future-time') {
   await assert.rejects(() => sync(initial), /bridge event observation time is invalid/);
   // Model a legacy direct publisher's malformed cache; the new RPC rejects it.
   await publishDirect(initial, {...(await integration()).metadata, identity_inventory_v1: initial.p_identity_inventory,
    last_inventory_count: initial.p_inventory_count, last_detector_count: initial.p_devices.length});
  } else await sync(initial);
  const next = await request({at: timestamp(index * 5000 + 1000), area: scenario === 'changed-area' ? 'Synthetic Other Area' : 'Synthetic Field', count: scenario === 'changed-membership' ? 3 : 2});
  assert.equal(next.p_identity_inventory.groups[0].bridgeLastEventAt, null);
  if (scenario === 'incoming-event') next.p_identity_inventory.groups[0].bridgeLastEventAt = timestamp(index * 5000 + 500);
  await sync(next); const row = await integration(), group = row.metadata.identity_inventory_v1.groups[0];
  assert.equal(group.bridgeLastEventAt, scenario === 'same-group' ? history : scenario === 'incoming-event' ? timestamp(index * 5000 + 500) : null, scenario);
  assert.equal(Date.parse(row.last_sync_at), Date.parse(next.p_observed_at));
  assert.equal(row.metadata.identity_inventory_v1.observedAt, next.p_observed_at);
  assert.notEqual(group.bridgeLastEventAt, next.p_observed_at);
 }
});

